"""Stage 35: assemble the Phase 3 results into the final report skeleton.

Reads what stages 30-34 wrote, plus the Phase 1 and Phase 2 tables, and lays
out every measured number in one document. Nothing here computes a metric; it
only arranges results that already exist, so the report cannot drift from them.

The four questions the final report has to answer are judgement, not
arithmetic, so this writes the tables and leaves the discussion to be written
by hand into report/final_report.md.

Usage:
    python scripts/35_final_report.py
    python scripts/35_final_report.py --force     # overwrite the written report
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, ".")

from common.io.paths import ensure_drive_mounted, lang_dir, work_dir
from common.log import kv, section, warn

LANGS = [("tel", "Telugu", "Model H"), ("nep", "Nepali", "Model L")]


def load(path) -> dict:
    p = Path(path)
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception:
        return {}


def pct(x) -> str:
    return f"{x:.1%}" if isinstance(x, (int, float)) else "n/a"


def num(x, fmt="{:.4f}") -> str:
    return fmt.format(x) if isinstance(x, (int, float)) else "n/a"


def copy_finetune_configs(work: str) -> list:
    """Bring the config saved beside each finetuned checkpoint into the repo."""
    out = []
    for code, _, _ in LANGS:
        src = Path(f"{work}/{lang_dir(code)}/7_checkpoints/config_{code}_ft.yaml")
        if src.exists():
            dst = Path(f"{lang_dir(code)}/configs/finetune_trained.yaml")
            shutil.copyfile(src, dst)
            out.append(str(dst))
    return out


def table(header: list, rows: list) -> list:
    """A markdown table as a list of lines."""
    return (["| " + " | ".join(header) + " |",
             "|" + "|".join(["---"] * len(header)) + "|"]
            + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--work", default=None)
    ap.add_argument("--out", default="report/final_report.md")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    ensure_drive_mounted()
    work = args.work or work_dir()
    tabs = Path("report/tables")

    corpus = {c: load(tabs / f"corpus_{c}.json") for c, _, _ in LANGS}
    lm = {c: load(tabs / f"lm_eval_{c}.json") for c, _, _ in LANGS}
    gen = {c: load(tabs / f"generation_{c}.json") for c, _, _ in LANGS}
    data = {c: load(tabs / f"reasoning_dataset_{c}.json") for c, _, _ in LANGS}
    ft = {c: load(tabs / f"finetune_{c}.json") for c, _, _ in LANGS}
    reason = {c: load(tabs / f"reasoning_{c}.json") for c, _, _ in LANGS}
    attn = {c: load(tabs / f"attention_compare_{c}.json") for c, _, _ in LANGS}
    abl = {c: load(tabs / f"ablation_{c}.json") for c, _, _ in LANGS}

    for label, src in (("reasoning dataset", data), ("finetuning log", ft),
                       ("reasoning evaluation", reason),
                       ("attention comparison", attn)):
        for code, name, _ in LANGS:
            if not src[code]:
                warn(f"no {label} for {name}; that section will be empty")

    d = ["# Phase 3 — Reasoning Finetuning, Attention Analysis and Final Report",
         "",
         "Each pretrained model was finetuned on its own synthetic reasoning "
         "dataset, in its own language, with its own tokenizer left unchanged. "
         "No data, no weights and no vocabulary crossed between the two.", ""]

    # ---------------- dataset ----------------
    d += ["## 1. Synthetic reasoning dataset", ""]
    for code, name, tier in LANGS:
        card = data[code]
        if not card:
            continue
        s = card["splits"]
        d += [f"### {name} ({tier})", "",
              f"Generated by `scripts/30_make_reasoning.py` from "
              f"`{lang_dir(code)}/configs/reasoning.yaml`, seed "
              f"`{card.get('seed')}`.", ""]
        d += table(["split", "examples", "template families", "distinct entities",
                    "mean length (chars)", "best constant answer"],
                   [[split, f"{s[split]['examples']:,}",
                     len(s[split]["by_template"]),
                     card["leakage"]["entities_per_split"][split],
                     f"{s[split]['mean_chars']:.0f}",
                     pct(s[split]["majority_answer_share"])]
                    for split in ("train", "val", "test")]) + [""]
        d += table(["template family", "train", "validation", "test", "what it tests"],
                   [[t["id"], s["train"]["by_template"].get(t["id"], 0),
                     s["val"]["by_template"].get(t["id"], 0),
                     s["test"]["by_template"].get(t["id"], 0),
                     t["description"]] for t in card["templates"]]) + [""]
        lk = card["leakage"]
        d += ["Leakage controls, checked rather than assumed:", "",
              f"- entity pools shared between train and test: "
              f"{len(lk['entity_overlap']['train_test'])}",
              f"- prompts repeated between train and test: "
              f"{lk['prompt_overlap_counts']['train_test']}",
              f"- template families held out of training: "
              f"{', '.join(lk['held_out_families']) or 'none'}", ""]

    # ---------------- finetuning ----------------
    d += ["## 2. Finetuning", ""]
    rows = []
    for code, name, _ in LANGS:
        f = ft[code]
        if not f:
            continue
        h = f["hyperparameters"]
        rows.append([name, f["started_from"]["checkpoint"],
                     f"{f['started_from']['step']:,}", f"{f['steps']:,}",
                     f"{h['learning_rate']:g}",
                     h["batch_size"] * h["grad_accum_steps"],
                     num(f["best_val_loss"]), f"{f['minutes']:.0f}"])
    if rows:
        d += table(["model", "started from", "pretrain step", "finetune steps",
                    "learning rate", "effective batch", "best val loss",
                    "minutes"], rows) + [""]
        d += ["Loss is taken on the answer tokens only; the prompt is given, "
              "not predicted. Full hyperparameters are in "
              "`report/tables/finetune_*.json` and in the config saved beside "
              "each checkpoint.", ""]

    # ---------------- reasoning results ----------------
    d += ["## 3. Reasoning results", ""]
    for code, name, tier in LANGS:
        r = reason[code]
        if not r:
            continue
        pre = r["models"]["pretrained"]
        fine = r["models"]["finetuned"]
        d += [f"### {name} ({tier})", "",
              f"Test split, {r['n']:,} examples with disjoint entities and one "
              f"held-out relation pattern.", ""]
        d += table(["measurement", "pretrained", "finetuned", "change"],
                   [["exact match, greedy generation",
                     pct(pre["generation"]["accuracy"]),
                     pct(fine["generation"]["accuracy"]),
                     f"{fine['generation']['accuracy'] - pre['generation']['accuracy']:+.1%}"],
                    ["likelihood-ranked choice",
                     pct(pre["choice"]["accuracy"]),
                     pct(fine["choice"]["accuracy"]),
                     f"{fine['choice']['accuracy'] - pre['choice']['accuracy']:+.1%}"],
                    ["random choice baseline",
                     pct(r["baselines"]["random_choice"]), "", ""],
                    ["best constant answer",
                     pct(r["baselines"]["majority_answer"]), "", ""],
                    ["always the first entity named",
                     pct(r["baselines"]["first_mentioned"]), "", ""]]) + [""]
        fams = sorted(fine["generation"]["by_template"])
        d += table(["template family", "n", "pretrained", "finetuned", "change"],
                   [[f, fine["generation"]["by_template"][f]["n"],
                     pct(pre["generation"]["by_template"][f]["accuracy"]),
                     pct(fine["generation"]["by_template"][f]["accuracy"]),
                     f"{fine['generation']['by_template'][f]['accuracy'] - pre['generation']['by_template'][f]['accuracy']:+.1%}"]
                    for f in fams]) + [""]
        d += table(["statements to combine", "n", "pretrained", "finetuned"],
                   [[h, fine["generation"]["by_hops"][h]["n"],
                     pct(pre["generation"]["by_hops"][h]["accuracy"]),
                     pct(fine["generation"]["by_hops"][h]["accuracy"])]
                    for h in sorted(fine["generation"]["by_hops"])]) + [""]

    if all(reason[c] for c, _, _ in LANGS):
        d += ["### Model H against Model L", ""]
        d += table(["measurement"] + [n for _, n, _ in LANGS],
                   [["finetuned exact match"]
                    + [pct(reason[c]["models"]["finetuned"]["generation"]["accuracy"])
                       for c, _, _ in LANGS],
                    ["finetuned choice accuracy"]
                    + [pct(reason[c]["models"]["finetuned"]["choice"]["accuracy"])
                       for c, _, _ in LANGS],
                    ["held-out pattern (transitive_4)"]
                    + [pct(reason[c]["models"]["finetuned"]["generation"]
                           ["by_template"].get("transitive_4", {}).get("accuracy"))
                       for c, _, _ in LANGS],
                    ["test bits per byte, pretrained"]
                    + [num(lm[c].get("splits", {}).get("test", {})
                           .get("bits_per_byte")) for c, _, _ in LANGS]]) + [""]

    # ---------------- attention ----------------
    d += ["## 4. Attention, pretrained against finetuned", ""]
    for code, name, _ in LANGS:
        a = attn[code]
        if not a:
            continue
        s = a["summary"]
        n_heads = len(a["head_changes"])
        d += [f"### {name}", "",
              f"Measured on {a['prompts']['n']} comparative-reasoning prompts of "
              f"{a['prompts']['seq_len']} tokens.", ""]
        d += table(["statistic", "pretrained", "finetuned", "change"],
                   [["mean entropy (nats)",
                     num(s["mean_entropy_pretrained"], "{:.3f}"),
                     num(s["mean_entropy_finetuned"], "{:.3f}"),
                     f"{s['mean_entropy_finetuned'] - s['mean_entropy_pretrained']:+.3f}"],
                    ["mean attention distance (positions)",
                     num(s["mean_distance_pretrained"], "{:.2f}"),
                     num(s["mean_distance_finetuned"], "{:.2f}"),
                     f"{s['mean_distance_finetuned'] - s['mean_distance_pretrained']:+.2f}"],
                    ["heads that sharpened", f"{s['heads_more_focused']} of {n_heads}",
                     "", ""],
                    ["heads that became more local",
                     f"{s['heads_more_local']} of {n_heads}", "", ""]]) + [""]
        d += table(["layer", "entropy before", "entropy after", "distance before",
                    "distance after"],
                   [[p["layer"], num(p["entropy"], "{:.3f}"),
                     num(f_["entropy"], "{:.3f}"),
                     num(p["mean_distance"], "{:.2f}"),
                     num(f_["mean_distance"], "{:.2f}")]
                    for p, f_ in zip(a["pretrained"]["layer_means"],
                                     a["finetuned"]["layer_means"])]) + [""]
        d += [f"Heatmaps: `report/figures/reasoning_attention_early_{code}_"
              f"pretrained.png` and `..._finetuned.png`, and the same pair for "
              f"the late layer.", ""]

    # ---------------- ablation ----------------
    ablated = {c: a for c, a in abl.items() if a}
    if ablated:
        d += ["## 5. Bonus ablation: no positional embeddings", ""]
        for code, a in ablated.items():
            std, ab = a["standard"], a["ablated"]
            d += [f"### {dict((c, n) for c, n, _ in LANGS)[code]}", "",
                  f"Same corpus, tokenizer, architecture, seed and schedule; the "
                  f"only difference is that the ablated model has no positional "
                  f"embedding table ({std['parameters'] - ab['parameters']:,} "
                  f"fewer parameters).", ""]
            d += table(["metric", "standard", "no positions", "change"],
                       [[label,
                         num(std["lm"]["test"][key]),
                         num(ab["lm"]["test"][key]),
                         f"{ab['lm']['test'][key] - std['lm']['test'][key]:+.4f}"]
                        for key, label in
                        (("cross_entropy_nats", "cross-entropy (nats)"),
                         ("perplexity", "perplexity"),
                         ("bits_per_byte", "bits per byte"))]) + [""]
            d += table(["metric", "standard", "no positions", "change"],
                       [[label, num(std["generation"]["greedy"][key]),
                         num(ab["generation"]["greedy"][key]),
                         f"{ab['generation']['greedy'][key] - std['generation']['greedy'][key]:+.4f}"]
                        for key, label in (("bleu", "BLEU-4"),
                                           ("chrf_pp", "chrF++"),
                                           ("rouge_l_f", "ROUGE-L"),
                                           ("distinct_1", "distinct-1"),
                                           ("distinct_2", "distinct-2"),
                                           ("repetition_4gram", "4-gram repetition"))]) + [""]
            d += table(["attention statistic", "standard", "no positions"],
                       [["mean entropy (nats)",
                         num(std["attention"]["entropy"], "{:.3f}"),
                         num(ab["attention"]["entropy"], "{:.3f}")],
                        ["mean distance (positions)",
                         num(std["attention"]["distance"], "{:.2f}"),
                         num(ab["attention"]["distance"], "{:.2f}")]]) + [""]

    d += ["## 6. Discussion", "",
          "To be written by hand, covering: how data scale and quality differed "
          "between the two models, how "
          "language-modelling and reasoning results compare across the two "
          "resource tiers, which tokenizer and corpus factors most affected the "
          "lower-resource model, and what evidence explains the differences.", ""]

    copied = copy_finetune_configs(work)

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(d) + "\n"
    if out.exists() and not args.force:
        alt = out.with_name(out.stem + "_generated.md")
        alt.write_text(text, encoding="utf-8")
        section("Report")
        print(f"  {out} already exists and was left alone.\n"
              f"  The freshly generated version is at {alt}.\n"
              f"  Pass --force to overwrite the report itself.")
    else:
        out.write_text(text, encoding="utf-8")
        section("Report")
        kv("written", out)
    kv("lines", len(d))
    for path in copied:
        kv("config copied", path)


if __name__ == "__main__":
    main()
